"""
Defensive Rule Generator for SOC Incident Containment.
Generates copy-ready YARA rules, Sigma YAML detection signatures, and multi-platform firewall block commands.
"""
import re
import uuid
from datetime import datetime, timezone
from typing import Dict, Any, Optional


def generate_yara_rule(ioc: str, ioc_type: str = "HASH", telemetry: Optional[Dict[str, Any]] = None) -> str:
    """
    Generates a syntactically valid YARA rule (.yar) matching the target indicator.
    Supports file hashes, string patterns, and malware family metadata.
    """
    telemetry = telemetry or {}
    sanitized_id = re.sub(r"[^a-zA-Z0-9_]", "_", ioc).strip("_")
    if not sanitized_id or sanitized_id[0].isdigit():
        rule_name = f"CyberPulse_Rule_{sanitized_id[:24]}"
    else:
        rule_name = f"CyberPulse_{sanitized_id[:32]}"

    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    
    # Extract threat tags or malware family if available
    vt_data = telemetry.get("vt", {}) or telemetry.get("virustotal", {})
    otx_data = telemetry.get("otx", {}) or telemetry.get("alienvault", {})
    risk_data = telemetry.get("risk", {})
    
    families = otx_data.get("malware_families", []) or []
    family_str = ", ".join(families) if families else "Generic Suspicious Indicator"
    severity = risk_data.get("level", "High")
    score = risk_data.get("score", "N/A")

    is_hash = ioc_type.upper() in ("MD5", "SHA1", "SHA256", "HASH")

    safe_ioc = ioc.replace("\\", "\\\\").replace('"', '\\"')
    safe_family = family_str.replace("\\", "\\\\").replace('"', '\\"')

    # Strings section
    if is_hash:
        strings_lines = [f'        $hash_ref = "{safe_ioc}" ascii wide nocase']
        if families:
            for idx, fam in enumerate(families[:3]):
                clean_fam = fam.replace("\\", "\\\\").replace('"', '\\"')
                strings_lines.append(f'        $malware_family_{idx+1} = "{clean_fam}" ascii wide nocase')
        strings_block = "    strings:\n" + "\n".join(strings_lines)
    else:
        # For domain, URL or string indicator
        strings_block = f"""    strings:
        $indicator = "{safe_ioc}" ascii wide nocase"""

    yara_content = f"""rule {rule_name}
{{
    meta:
        description = "Automated SOC defensive rule generated by CyberPulse CTI"
        author = "CyberPulse CTI Engine"
        reference = "CyberPulse Threat Intelligence Platform"
        date = "{date_str}"
        indicator = "{safe_ioc}"
        indicator_type = "{ioc_type}"
        malware_family = "{safe_family}"
        threat_score = "{score}"
        threat_level = "{severity}"
        tlp = "TLP:AMBER"

{strings_block}

    condition:
        any of them
}}
"""
    return yara_content.strip()


def generate_sigma_rule(ioc: str, ioc_type: str = "DOMAIN", telemetry: Optional[Dict[str, Any]] = None) -> str:
    """
    Generates a standardized YAML Sigma rule for SIEM detection.
    Supports DNS queries, web proxy requests, network connections, or process command lines.
    """
    telemetry = telemetry or {}
    rule_id = str(uuid.uuid4())
    date_str = datetime.now(timezone.utc).strftime("%Y/%m/%d")

    risk_data = telemetry.get("risk", {})
    score = risk_data.get("score", 75)
    if isinstance(score, (int, float)):
        if score >= 70:
            level = "high" if score < 90 else "critical"
        elif score >= 30:
            level = "medium"
        else:
            level = "low"
    else:
        level = "high"

    clean_ioc = re.sub(r"[\r\n\x00-\x1f]", "", ioc.strip()).replace("'", "''")
    safe_yaml_title = clean_ioc.replace('"', '\\"')

    ioc_t = ioc_type.upper()
    if ioc_t in ("IPV4", "IPV6"):
        logsource = """logsource:
    category: firewall
    product: any"""
        detection_block = f"""detection:
    selection:
        DestinationIp: '{clean_ioc}'
    condition: selection"""
        tags = [
            "attack.command_and_control",
            "attack.t1071"
        ]
    elif ioc_t == "URL":
        logsource = """logsource:
    category: proxy
    product: any"""
        detection_block = f"""detection:
    selection:
        c-uri: '*{clean_ioc}*'
    condition: selection"""
        tags = [
            "attack.initial_access",
            "attack.t1566.002",
            "attack.command_and_control"
        ]
    elif ioc_t in ("MD5", "SHA1", "SHA256", "HASH"):
        logsource = """logsource:
    category: process_creation
    product: windows"""
        if ioc_t == "SHA256" or (ioc_t == "HASH" and len(clean_ioc) == 64):
            hash_field = "Hashes.SHA256"
        elif ioc_t == "MD5" or (ioc_t == "HASH" and len(clean_ioc) == 32):
            hash_field = "Hashes.MD5"
        elif ioc_t == "SHA1" or (ioc_t == "HASH" and len(clean_ioc) == 40):
            hash_field = "Hashes.SHA1"
        else:
            hash_field = "Hashes.SHA256"

        detection_block = f"""detection:
    selection:
        {hash_field}: '{clean_ioc}'
    condition: selection"""
        tags = [
            "attack.execution",
            "attack.t1204.002"
        ]
    else:  # DOMAIN
        logsource = """logsource:
    category: dns
    product: any"""
        detection_block = f"""detection:
    selection:
        query: '{clean_ioc}'
    condition: selection"""
        tags = [
            "attack.command_and_control",
            "attack.t1071.001"
        ]

    tag_yaml = "\n".join([f"    - {t}" for t in tags])

    needs_quotes = any(c in safe_yaml_title for c in (": ", "#", "{", "}", "[", "]", "*", "?", ",", "&", "!")) or safe_yaml_title.startswith(("@", "`", "|", ">", "%", "-", " "))
    if needs_quotes:
        title_line = f'title: "CyberPulse Detection - {safe_yaml_title}"'
        desc_line = f'description: "Detects malicious network activity, DNS requests, or execution related to {safe_yaml_title}"'
    else:
        title_line = f"title: CyberPulse Detection - {safe_yaml_title}"
        desc_line = f"description: Detects malicious network activity, DNS requests, or execution related to {safe_yaml_title}"

    sigma_yaml = f"""{title_line}
id: {rule_id}
status: experimental
{desc_line}
references:
    - https://cyberpulse.local/ioc/{clean_ioc}
author: CyberPulse CTI Platform
date: {date_str}
tags:
{tag_yaml}
{logsource}
{detection_block}
falsepositives:
    - Unknown
level: {level}
"""
    return sigma_yaml.strip()


def generate_firewall_commands(ip: str) -> Dict[str, str]:
    """
    Generates multi-platform perimeter containment commands for IP indicators.
    Includes Windows PowerShell, Linux (iptables/ip6tables), and Cisco IOS ACL (IPv4/IPv6).
    Safely suppresses destructive blocking for loopback addresses (127.0.0.0/8, ::1).
    """
    clean_ip = ip.strip()
    safe_name = re.sub(r"[^a-zA-Z0-9_]", "_", clean_ip).strip("_")
    is_ipv6 = ":" in clean_ip

    # Check loopback
    is_loop = False
    clean_strip = clean_ip.split("%")[0].strip("[]")
    if clean_strip in ("127.0.0.1", "::1", "localhost") or clean_strip.startswith("127."):
        is_loop = True
    else:
        try:
            import ipaddress
            ip_obj = ipaddress.ip_address(clean_strip)
            if ip_obj.is_loopback:
                is_loop = True
        except ValueError:
            pass

    if is_loop:
        powershell_cmd = (
            f'# Local loopback asset ({clean_ip}) - perimeter firewall block suppressed.\n'
            f'# Dropping 127.0.0.1 disrupts local host inter-process communication.\n'
            f'# Inspect local active port listeners:\n'
            f'Get-NetTCPConnection -LocalAddress "{clean_ip}"'
        )
        iptables_cmd = (
            f"# CyberPulse Loopback Asset Protection ({clean_ip})\n"
            f"# Perimeter firewall DROP suppressed (blocking 127.0.0.1 disrupts local networking).\n"
            f"# Inspect local listening ports:\n"
            f"netstat -tulnp | grep {clean_ip}"
        )
        cisco_acl_cmd = (
            f"! CyberPulse Loopback Host ({clean_ip})\n"
            f"! Localhost is non-routable on edge infrastructure (RFC 1122 / RFC 4291)."
        )
        return {
            "powershell": powershell_cmd,
            "iptables": iptables_cmd,
            "cisco_acl": cisco_acl_cmd
        }

    powershell_cmd = (
        f'New-NetFirewallRule -DisplayName "CyberPulse_Block_{safe_name}" '
        f'-Direction Outbound -RemoteAddress "{clean_ip}" -Action Block '
        f'-Description "Automated perimeter block for high-risk IOC {clean_ip}"'
    )

    if is_ipv6:
        iptables_cmd = (
            f"# CyberPulse IOC Perimeter Containment (IPv6)\n"
            f"ip6tables -A OUTPUT -d {clean_ip} -j DROP\n"
            f"ip6tables -A INPUT -s {clean_ip} -j DROP"
        )
        cisco_acl_cmd = (
            f"! CyberPulse IPv6 ACL Containment Rule\n"
            f"ipv6 access-list CYBERPULSE_BLOCK_V6\n"
            f" deny ipv6 any host {clean_ip}\n"
            f" deny ipv6 host {clean_ip} any"
        )
    else:
        iptables_cmd = (
            f"# CyberPulse IOC Perimeter Containment\n"
            f"iptables -A OUTPUT -d {clean_ip} -j DROP\n"
            f"iptables -A INPUT -s {clean_ip} -j DROP"
        )
        cisco_acl_cmd = (
            f"! CyberPulse ACL Containment Rule\n"
            f"access-list 100 deny ip any host {clean_ip}\n"
            f"access-list 100 deny ip host {clean_ip} any"
        )

    return {
        "powershell": powershell_cmd,
        "iptables": iptables_cmd,
        "cisco_acl": cisco_acl_cmd
    }


def generate_all_defensive_rules(ioc: str, ioc_type: str, telemetry: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """
    Master helper generating all applicable rules based on indicator classification.
    """
    telemetry = telemetry or {}
    ioc_t = ioc_type.upper()

    yara = generate_yara_rule(ioc, ioc_t, telemetry)
    sigma = generate_sigma_rule(ioc, ioc_t, telemetry)
    firewall = generate_firewall_commands(ioc) if ioc_t in ("IPV4", "IPV6") else None

    return {
        "ioc": ioc,
        "ioc_type": ioc_t,
        "yara": yara,
        "sigma": sigma,
        "firewall": firewall
    }
